const assert=require('node:assert/strict');
const {validate,defaults,safeURL,embedURL}=require('../server/live-broadcast');
const calendar=require('../broadcast-calendar');
assert.deepEqual(validate(defaults),defaults);
assert.equal(defaults.status,'unconfigured');assert.equal(defaults.startsAt,null);assert.equal(defaults.replays.length,0);
for(const url of ['javascript:alert(1)','http://example.com','https://localhost/x','https://127.0.0.1/x','https://example.com:3100','https://user:password@example.com/x','https://[::1]/x'])assert.throws(()=>safeURL(url));
assert.equal(safeURL(' https://example.com/watch '),'https://example.com/watch');
assert.equal(embedURL('https://youtu.be/dQw4w9WgXcQ'),'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ?playsinline=1&rel=0&autoplay=1');
assert.equal(embedURL('https://www.youtube.com/live/dQw4w9WgXcQ'),embedURL('https://youtu.be/dQw4w9WgXcQ'));
assert.equal(embedURL('https://evil.example/watch?v=dQw4w9WgXcQ'),'');assert.equal(embedURL('https://youtube.com/watch?v=invalid'),'');
assert.equal(embedURL('https://vimeo.com/123456/abcd'),'https://player.vimeo.com/video/123456?dnt=1&autoplay=1&h=abcd');
assert.throws(()=>validate({...defaults,status:'scheduled'}),/real broadcast URL/);
assert.throws(()=>validate({...defaults,status:'scheduled',streamUrl:'https://example.com'}),/start time/);
assert.throws(()=>validate({...defaults,streamUrl:'https://example.com'}),/publish/);
assert.throws(()=>validate({...defaults,status:'fake'}),/status/);
assert.throws(()=>validate({...defaults,startsAt:NaN}),/date/);
assert.throws(()=>validate({...defaults,startsAt:Infinity}),/date/);
assert.throws(()=>validate({...defaults,heroPhotoUrl:'/uploads/../test.jpg'}),/uploaded/);
assert.throws(()=>validate({...defaults,schedule:[defaults.schedule[0],defaults.schedule[0]]}),/unique ID/);
assert.throws(()=>validate({...defaults,schedule:Array(13).fill(defaults.schedule[0])}),/12/);
assert.throws(()=>validate({...defaults,replays:Array(31).fill({})}),/30/);
assert.throws(()=>validate({...defaults,replays:[{id:'replay-1',title:'Replay',startsAt:null,url:'',duration:'',posterUrl:''}]}),/replay URL/);
const start=Date.parse('2027-01-09T10:00:00Z');
assert.throws(()=>validate({...defaults,schedule:[{...defaults.schedule[0],startsAt:start,endsAt:start}]}),/end must/);
const data=validate({...defaults,status:'scheduled',startsAt:start,streamUrl:'https://example.com/watch?a=1&b=2',schedule:[{...defaults.schedule[0],title:'Wedding, vows; ♥\nFamily',startsAt:start,endsAt:start+3600000}],intro:'♥'.repeat(100)+'\nDESCRIPTION:injected'});
const ics=calendar(data,{reminder:true,now:start-60000});
assert.match(ics,/DTSTART:20270109T100000Z/);assert.match(ics,/DTEND:20270109T110000Z/);assert.match(ics,/TRIGGER:-PT15M/);assert.match(ics,/Wedding\\, vows\\; ♥\\nFamily/);
assert.ok(!ics.includes('\r\nDESCRIPTION:injected'));assert.ok(ics.split('\r\n').every(line=>Buffer.byteLength(line)<=75));
assert.throws(()=>calendar(defaults),/not been announced/);
assert.match(calendar({...data,schedule:[]}),/UID:sj-live-main/);
assert.ok(!calendar(data).includes('VALARM'));
console.log('PASS live-broadcast defaults, validation, safe URLs/embeds, status constraints, row limits, calendar UTC/escaping/folding/reminders');
